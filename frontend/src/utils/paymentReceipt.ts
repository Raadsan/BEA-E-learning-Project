export function downloadPaymentReceipt(row: PaymentReceiptData) {
  const html = buildPaymentReceiptHtml(row);
  const blob = new Blob([html], { type: "text/html;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const txId = row.transaction_id || row.provider_transaction_id || row.id || "receipt";
  const link = document.createElement("a");
  link.href = url;
  link.download = `BEA-Receipt-${txId}.html`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function printPaymentReceipt(row: PaymentReceiptData) {
  const html = buildPaymentReceiptHtml(row);
  const win = window.open("", "_blank", "noopener,noreferrer,width=900,height=700");
  if (!win) {
    downloadPaymentReceipt(row);
    return;
  }
  win.document.write(html);
  win.document.close();
}
