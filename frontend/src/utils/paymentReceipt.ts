export type PaymentReceiptData = {
  id?: number | string;
  student_name?: string;
  student_id?: string;
  email?: string;
  program_name?: string;
  package_name?: string;
  amount?: number | string;
  method?: string;
  payment_method?: string;
  status?: string;
  created_at?: string;
  payment_date?: string;
  provider_transaction_id?: string;
  transaction_id?: string;
  payer_phone?: string;
  currency?: string;
};

function formatMoney(amount?: number | string) {
  return `$${Number(amount || 0).toFixed(2)}`;
}

function formatDate(value?: string) {
  if (!value) return "N/A";
  return new Date(value).toLocaleString("en-GB", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

function formatMethod(row: PaymentReceiptData) {
  const method = (row.payment_method || row.method || "N/A").toUpperCase();
  if (method.includes("WAAFI")) return "WAAFI";
  if (method === "EVC") return "EVC";
  if (method === "BANK") return "BANK";
  return method;
}

